FARE_RATE = 14

name = input("Enter passenger name: ")

while name.strip() == "":
    print("Please input your name without special characters or numbers")
    name = input("Enter passenger name: ")

distance = float(input("Enter distance (km): "))

while distance <= 0:
    print("Please make sure your distance is a positive number")
    distance = float(input("Enter distance (km): "))

passengers = int(input("Enter number of passengers: "))

while passengers <= 0:
    print("Please make sure the amount of passengers is a positive whole number")
    passengers = int(input("Enter number of passengers: "))

total_fare = distance * FARE_RATE * passengers

print("Passenger:", name)
print("Total Fare: PHP", round(total_fare, 2))